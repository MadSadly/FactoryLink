CREATE TABLE IF NOT EXISTS USER_ACCOUNT (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  email VARCHAR(255) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  name VARCHAR(100) NOT NULL,
  role VARCHAR(20) NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS FACTORY (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  user_id BIGINT NOT NULL,
  name VARCHAR(100) NOT NULL,
  location VARCHAR(100) NOT NULL,
  business_type VARCHAR(100) NOT NULL,
  description TEXT,
  CONSTRAINT fk_factory_user FOREIGN KEY (user_id) REFERENCES USER_ACCOUNT(id)
);

CREATE TABLE IF NOT EXISTS PART (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  factory_id BIGINT NOT NULL,
  name VARCHAR(120) NOT NULL,
  category VARCHAR(80) NOT NULL,
  price DECIMAL(12,2) NOT NULL,
  stock INT NOT NULL DEFAULT 0,
  CONSTRAINT fk_part_factory FOREIGN KEY (factory_id) REFERENCES FACTORY(id)
);

CREATE TABLE IF NOT EXISTS CHAT_ROOM (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  buyer_id BIGINT NOT NULL,
  seller_id BIGINT NOT NULL,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_chat_room_buyer FOREIGN KEY (buyer_id) REFERENCES USER_ACCOUNT(id),
  CONSTRAINT fk_chat_room_seller FOREIGN KEY (seller_id) REFERENCES USER_ACCOUNT(id)
);

CREATE TABLE IF NOT EXISTS CHAT_MESSAGE (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  room_id BIGINT NOT NULL,
  sender_id BIGINT NOT NULL,
  message TEXT NOT NULL,
  timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_chat_message_room FOREIGN KEY (room_id) REFERENCES CHAT_ROOM(id),
  CONSTRAINT fk_chat_message_sender FOREIGN KEY (sender_id) REFERENCES USER_ACCOUNT(id)
);

CREATE TABLE IF NOT EXISTS CONTRACT (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  buyer_id BIGINT NOT NULL,
  seller_id BIGINT NOT NULL,
  content TEXT NOT NULL,
  status VARCHAR(40) NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_contract_buyer FOREIGN KEY (buyer_id) REFERENCES USER_ACCOUNT(id),
  CONSTRAINT fk_contract_seller FOREIGN KEY (seller_id) REFERENCES USER_ACCOUNT(id)
);
